// The server's CA certificate lives in src/commonMain/certs/server-ca.pem and is compiled into the
// SERVER_CA_PEM constant, so no platform has to load it from a file at runtime. Refresh it with
//   ./gradlew :sharedLogic:syncServerCa
val serverCaPem = layout.projectDirectory.file("src/commonMain/certs/server-ca.pem")

val generateServerCa = tasks.register("generateServerCa") {
    description = "Generates SERVER_CA_PEM from src/commonMain/certs/server-ca.pem."
    val pemFile = serverCaPem
    val outputDir = layout.buildDirectory.dir("generated/serverCa/commonMain/kotlin")
    inputs.file(pemFile)
    outputs.dir(outputDir)
    doLast {
        val pem = pemFile.asFile.readText().trim()
        if (!pem.startsWith("-----BEGIN CERTIFICATE-----") || '$' in pem || "\"\"\"" in pem) {
            throw GradleException("${pemFile.asFile} must contain PEM certificates only.")
        }
        val source = outputDir.get().file("com/chencohensolution/journal/tls/ServerCa.kt").asFile
        source.parentFile.mkdirs()
        source.writeText(
            """
            |// Generated by :sharedLogic:generateServerCa from src/commonMain/certs/server-ca.pem. Do not edit.
            |package com.chencohensolution.journal.tls
            |
            |/** CA that signed the journal server certificate; trusted in addition to the platform roots. */
            |internal const val SERVER_CA_PEM: String = ${"\"\"\""}
            |$pem
            |${"\"\"\""}
            |""".trimMargin()
        )
    }
}
kotlin.sourceSets.commonMain { kotlin.srcDir(generateServerCa) }

val serverCaFile: File = rootProject.file(
    (findProperty("journalServerDir") as String? ?: "../journal-server-go") + "/certs/ca.pem"
)

// Separate task for the same reason as checkServerSchemaDir below.
val checkServerCaFile = tasks.register("checkServerCaFile") {
    val caFile = serverCaFile
    doLast {
        if (!caFile.isFile) {
            throw GradleException("Server CA not found at $caFile. Pass -PjournalServerDir=<path to journal-server-go>.")
        }
    }
}

tasks.register<Copy>("syncServerCa") {
    group = "build setup"
    description = "Copies certs/ca.pem from journal-server-go to src/commonMain/certs/server-ca.pem."
    dependsOn(checkServerCaFile)
    from(serverCaFile) { rename { "server-ca.pem" } }
    into(serverCaPem.asFile.parentFile)
}

// The server repo owns the GraphQL schema (gqlgen is schema-first). Copy it here and commit the result:
//   ./gradlew :sharedLogic:syncServerSchema
// Override the server checkout location with -PjournalServerDir=<path> (default: sibling journal-server-go).
val serverSchemaDir: File = rootProject.file(
    (findProperty("journalServerDir") as String? ?: "../journal-server-go") + "/graph/schema"
)

// Separate task because Copy skips its own actions (NO-SOURCE) when the source folder is missing.
val checkServerSchemaDir = tasks.register("checkServerSchemaDir") {
    val schemaDir = serverSchemaDir
    doLast {
        if (!schemaDir.isDirectory) {
            throw GradleException("Server schema not found at $schemaDir. Pass -PjournalServerDir=<path to journal-server-go>.")
        }
    }
}

tasks.register<Copy>("syncServerSchema") {
    group = "apollo"
    description = "Copies the GraphQL schema from journal-server-go into src/commonMain/graphql."
    dependsOn(checkServerSchemaDir)

    from(serverSchemaDir) {
        include("*.graphql")
        // Apollo only treats *.graphqls as schema; *.graphql files are operations.
        rename { it.removeSuffix(".graphql") + ".graphqls" }
    }
    into(layout.projectDirectory.dir("src/commonMain/graphql"))
}

